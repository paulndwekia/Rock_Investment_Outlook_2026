from pathlib import Path
from datetime import datetime
import csv
import json
import re
import time
from playwright.sync_api import sync_playwright

PROJECT = Path.home() / "Desktop" / "Rock_Investment_Outlook_2026"
DATA = PROJECT / "data"
RAW = DATA / "raw"
TABLES = RAW / "tables"
SHOTS = DATA / "screenshots"

for p in [TABLES, SHOTS]:
    p.mkdir(parents=True, exist_ok=True)

URL = "https://www.rockdataplus.com/repository"

MODULES = [
    "Stock Market",
    "Agriculture",
    "Exchange Rates",
    "Inflation",
    "Historical PMI",
    "NSE Bond Index",
    "Treasury Bills",
    "Yield Curve",
    "Liquidity Indicators",
    "Forex Reserves",
    "Fuel Prices",
]

def clean_name(x):
    x = re.sub(r"[^\w\s.-]", "", x)
    return re.sub(r"\s+", "_", x.strip())

def save_shot(page, name):
    try:
        page.screenshot(
            path=str(
                SHOTS / f"{clean_name(name)}_{datetime.now():%Y%m%d_%H%M%S}.png"
            ),
            full_page=True
        )
    except:
        pass

def save_tables(page, module):
    tables = page.locator("table")
    for i in range(tables.count()):
        try:
            table = tables.nth(i)
            rows = table.locator("tr")

            if rows.count() == 0:
                continue

            filename = (
                f"{clean_name(module)}_"
                f"{datetime.now():%Y%m%d_%H%M%S}_"
                f"{i+1}.csv"
            )

            with (TABLES / filename).open(
                "w",
                newline="",
                encoding="utf-8-sig"
            ) as f:
                writer = csv.writer(f)

                for r in range(rows.count()):
                    cells = rows.nth(r).locator("th,td")
                    values = [
                        cells.nth(c).inner_text().strip()
                        for c in range(cells.count())
                    ]

                    if values:
                        writer.writerow(values)

            print("  Saved:", filename)

        except Exception as e:
            print("  Table error:", e)

def click_exact(page, text):
    try:
        loc = page.get_by_text(text, exact=True)

        for i in range(loc.count()):
            item = loc.nth(i)

            if item.is_visible():
                item.scroll_into_view_if_needed()
                item.click(timeout=5000)
                return True

    except:
        pass

    return False

def main():

    print("=" * 60)
    print("ROCK DATA PLUS — RELIABLE COLLECTION")
    print("=" * 60)

    with sync_playwright() as p:

        # Completely separate browser profile.
        # This avoids Chrome debugging/profile conflicts.
        context = p.chromium.launch_persistent_context(
            user_data_dir=str(PROJECT / ".rock_session"),
            headless=False,
            accept_downloads=True,
            viewport={"width": 1600, "height": 900}
        )

        page = context.pages[0] if context.pages else context.new_page()

        print("\nOpening Rock Data Plus...")
        page.goto(
            URL,
            wait_until="domcontentloaded",
            timeout=60000
        )

        print("""
============================================================
ROCK LOGIN
============================================================

The Rock Repository is open in the browser.

Log in normally using your Rock Data Plus account.
Your credentials stay in the browser.

After logging in, wait until the Repository shows:
"Analysis complete" / "Ready for Analysis".

Then return to this terminal.
""")

        input("Press ENTER when the Rock Repository is fully loaded... ")

        # Verify the Repository is actually visible.
        try:
            page.get_by_text(
                "Stock Market",
                exact=True
            ).first.wait_for(
                state="visible",
                timeout=30000
            )
        except:
            print("\nRock Repository was not detected.")
            save_shot(page, "repository_not_detected")
            input("Press ENTER to close...")
            context.close()
            return

        print("\n✓ Rock Repository detected.")

        # --------------------------------------------------
        # Capture responses generated by Rock
        # --------------------------------------------------

        captured = set()

        def response_handler(response):
            try:
                url = response.url.lower()
                content_type = response.headers.get(
                    "content-type", ""
                ).lower()

                if "json" not in content_type:
                    return

                # Don't save authentication/session data.
                blocked = [
                    "/auth/",
                    "/token",
                    "/session",
                    "/user"
                ]

                if any(x in url for x in blocked):
                    return

                body = response.body()

                if len(body) < 100:
                    return

                import hashlib

                digest = hashlib.sha256(body).hexdigest()

                if digest in captured:
                    return

                captured.add(digest)

                filename = (
                    f"{datetime.now():%Y%m%d_%H%M%S}_"
                    f"{len(captured):04d}.json"
                )

                (RAW / filename).write_bytes(body)

                print("  ✓ Rock response captured:", filename)

            except:
                pass

        page.on("response", response_handler)

        # --------------------------------------------------
        # Stock Market
        # --------------------------------------------------

        print("\n[1] Stock Market")

        click_exact(page, "Stock Market")
        page.wait_for_timeout(4000)

        for category in [
            "Equities Trading",
            "Bonds Trading",
            "Market Indices"
        ]:
            if click_exact(page, category):
                print("  ✓", category)

        page.wait_for_timeout(7000)
        save_tables(page, "Stock Market")
        save_shot(page, "Stock Market")

        # --------------------------------------------------
        # Other Rock modules
        # --------------------------------------------------

        for n, module in enumerate(MODULES[1:], 2):

            print(f"\n[{n}] {module}")

            if click_exact(page, module):
                print("  ✓ Opened")
                page.wait_for_timeout(5000)

                save_tables(page, module)
                save_shot(page, module)

            else:
                print("  - Module not found")

        # Give delayed requests time to finish.
        page.wait_for_timeout(10000)

        manifest = {
            "project": "Rock Investment Outlook 2026",
            "source": "Rock Data Plus",
            "repository": URL,
            "collection_date": datetime.now().isoformat(),
            "modules": MODULES,
            "raw_responses": len(list(RAW.glob("*.json"))),
            "tables": len(list(TABLES.glob("*.csv"))),
            "external_data_used": False
        }

        (DATA / "rock_manifest.json").write_text(
            json.dumps(manifest, indent=2),
            encoding="utf-8"
        )

        print("\n" + "=" * 60)
        print("COLLECTION FINISHED")
        print("=" * 60)

        print("\nRock data saved to:")
        print(DATA)

        print("\nRaw responses:")
        print(RAW)

        print("\nTables:")
        print(TABLES)

        print("\nManifest:")
        print(DATA / "rock_manifest.json")

        input("\nPress ENTER to close the browser...")

        context.close()

if __name__ == "__main__":
    main()
